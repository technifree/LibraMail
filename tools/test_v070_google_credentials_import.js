'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const planner = fs.readFileSync(path.join(root, 'resources/js/planner.js'), 'utf8');
const backend = fs.readFileSync(path.join(root, 'engine/backend.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'resources/index.html'), 'utf8');
function section(source, from, to) {
  const a = source.indexOf(from), b = source.indexOf(to, a + from.length);
  assert(a >= 0 && b > a, from);
  return source.slice(a, b);
}
const ID = '123-example.apps.googleusercontent.com';
const SECRET = 'synthetic-desktop-secret';
const fields = Object.fromEntries(['planner-google-client-id', 'planner-google-client-secret', 'btn-planner-google-import'].map(id => [id, {value: '', disabled: false}]));
const state = {googleManagedClient: false, googleOAuthBusy: false, googleCredentialImporting: false, googleOAuthFlowId: '', googleOAuthPollTimer: null};
const messages = [], responses = [], calls = [];
let poll;
const sandbox = vm.createContext({state, document: {getElementById: id => fields[id]}, googleStatus: (...args) => messages.push(args), t: key => key, readFileText: file => file.text(), stopGoogleOAuthPolling: () => {state.googleOAuthPollTimer = null;}, setGoogleOAuthBusy: busy => {state.googleOAuthBusy = busy;}, handleGoogleOAuthFlow: flow => responses.push(flow), setInterval: fn => {poll = fn; return 1;}, App: {rpc: (...args) => {calls.push(args); return sandbox.pending;}}});
vm.runInContext(section(planner, '  function startGoogleOAuthPolling(', '  async function connectGoogle('), sandbox);
const parse = sandbox.parseGoogleDesktopCredentials;
const importFile = sandbox.importGoogleDesktopCredentials;
const valid = JSON.stringify({installed:{client_id: ID, client_secret: SECRET, auth_uri:'https://untrusted.invalid',token_uri:'https://untrusted.invalid',redirect_uris:['https://untrusted.invalid']}});
const json = value => JSON.parse(JSON.stringify(value));
assert.deepEqual(json(parse(valid)), {clientId:ID,clientSecret:SECRET});
assert.deepEqual(json(parse('\uFEFF'+JSON.stringify({installed:{client_id:ID}}))), {clientId:ID,clientSecret:''});
for (const value of ['not json', '{}', 'null', '[]', JSON.stringify({web:{client_id:ID}}), JSON.stringify({web:{},installed:{client_id:ID}}), JSON.stringify({installed:{client_id:'evil.example'}}), JSON.stringify({installed:{client_id:ID,client_secret:['secret']}}), JSON.stringify({installed:{client_id:ID,client_secret:'bad\nsecret'}}), ' '.repeat(65537)]) assert.throws(() => parse(value));
function input(text, size=Buffer.byteLength(text)) {return {value:'fake-path', files:[{size,text:async()=>text}]};}
async function main() {
  const selected = input(valid);
  await importFile(selected);
  assert.equal(selected.value, '');
  assert.equal(fields['planner-google-client-id'].value, ID);
  assert.equal(fields['planner-google-client-secret'].value, SECRET);
  assert.equal(calls.length, 0, 'No RPC before explicit connection');
  assert.deepEqual(messages.at(-1), ['planner.googleCredentialsImported','success']);
  await importFile(input('{'+SECRET));
  assert.equal(fields['planner-google-client-id'].value, ID);
  assert.equal(fields['planner-google-client-secret'].value, SECRET);
  assert.deepEqual(messages.at(-1), ['planner.googleCredentialsInvalid','error']);
  assert(!JSON.stringify(messages).includes(SECRET));
  await importFile(input(valid, 65537));
  assert.equal(messages.at(-1)[0], 'planner.googleCredentialsInvalid');
  state.googleManagedClient = true;
  await importFile(input(JSON.stringify({installed:{client_id:'other.apps.googleusercontent.com'}})));
  assert.equal(fields['planner-google-client-id'].value, ID);
  state.googleManagedClient = false;
  let release;
  const delayed = importFile({value:'x',files:[{size:20,text:()=>new Promise(resolve=>{release=resolve;})}]});
  fields['planner-google-client-id'].value='manual edit';
  release(valid);
  await delayed;
  assert.equal(fields['planner-google-client-id'].value,'manual edit');
  assert.equal(fields['btn-planner-google-import'].disabled,false);
  // One outstanding poll at a time; responses from older flows must not alter the new one.
  let finish;
  sandbox.pending=new Promise(resolve=>{finish=resolve;});
  sandbox.startGoogleOAuthPolling('old');
  const oldPoll=poll();
  await poll();
  assert.equal(calls.length,1);
  sandbox.startGoogleOAuthPolling('new');
  finish({id:'old',status:'complete'});
  await oldPoll;
  assert.equal(responses.length,0);
  assert.equal(state.googleOAuthFlowId,'new');
  sandbox.pending=Promise.resolve({id:'new',status:'pending'});
  await poll();
  assert.deepEqual(json(responses),[{id:'new',status:'pending'}]);
  // Evaluate the actual backend RPC handlers with a simulated OAuth manager.
  const rpcSource=section(backend,"  'calendar.google.oauth.config':", "  'calendar.google.oauth.status':");
  let beginArgs;
  const env={LIBRAMAIL_GOOGLE_CALENDAR_CLIENT_ID:ID, LIBRAMAIL_GOOGLE_CALENDAR_CLIENT_SECRET:SECRET};
  const rpc=vm.runInNewContext('({'+rpcSource+'})',{process:{env},googleCalendarOAuthManager:{begin:async args=>{beginArgs=args;return {id:'test',authUrl:'https://accounts.google.com/'};}},openExternalWithSystem:async()=>{}});
  assert.deepEqual(json(await rpc['calendar.google.oauth.config']()),{clientId:ID});
  await rpc['calendar.google.oauth.begin']({clientId:'manual',clientSecret:'manual-secret'});
  assert.equal(beginArgs.clientId,ID);assert.equal(beginArgs.clientSecret,SECRET);
  delete env.LIBRAMAIL_GOOGLE_CALENDAR_CLIENT_SECRET;
  await rpc['calendar.google.oauth.begin']({clientId:'manual',clientSecret:'manual-secret'});
  assert.equal(beginArgs.clientSecret,'');
  delete env.LIBRAMAIL_GOOGLE_CALENDAR_CLIENT_ID;
  await rpc['calendar.google.oauth.begin']({clientId:'manual',clientSecret:'manual-secret'});
  assert.equal(beginArgs.clientId,'manual');assert.equal(beginArgs.clientSecret,'manual-secret');
  for(const key of ['googleClientIdHelp','googleConsoleOpen','googleCredentialsImport','googleCredentialsImported','googleCredentialsInvalid']) for(const lang of ['fr','en']) assert.equal(typeof JSON.parse(fs.readFileSync(path.join(root,`resources/locales/${lang}.json`),'utf8'))['planner.'+key],'string');
  for(const id of ['planner-google-manual-help','planner-google-credential-tools','planner-google-credentials-file','btn-planner-google-import','btn-planner-google-console']) assert(html.includes(`id="${id}"`));
  console.log('[OK] LibraMail 0.7.0 : import OAuth Google local, modes personnel/géré, confidentialité et polling isolé');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
